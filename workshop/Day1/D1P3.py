# Day1\D1P3.py
"""
FinDesk V3 - Finance Query Routing Assistant (classification + routing)
Day 1 / Session 3 - runnable checkpoint (D1P3.py)

WHAT THIS VERSION DOES
----------------------
Adds intelligence on top of the V2 sequential graph: every question is first
CLASSIFIED, then ROUTED to a category-specific processing node.

                 START
                   |
                   v
              Query Input
                   |
                   v
             Query Classifier        <- LLM structured output,
                   |                    keyword fallback on failure
            Conditional Routing
                   |
       +-----------+-----------+-----------+-----------+
       |           |           |           |           |
       v           v           v           v           v
    Policy      Invoice   Reimbursement  Budget     General/Unclear
     Node         Node        Node        Node        Node
       |           |           |           |           |
       +-----------+-----------+-----------+-----------+
                   |
                   v
              Final Output
                   |
                   v
                  END

CONCEPTS INTRODUCED
-------------------
  * State attributes beyond a single field (question/category/answers)
  * Conditional edges: add_conditional_edges() with a routing function
  * Structured classification via llm.with_structured_output(QueryClassification)
  * Provider-compatible fallback: keyword classifier if structured output fails
  * Node factories (make_answer_node) to avoid six copies of the same code
  * Path map: category name -> node name (edge labels in the graph drawing)

RUN
---
    python D1P3.py

COMMANDS
--------
    /steps      answer a question showing each node update
    /graph      print the graph structure
    /classify   classify a question without running the full graph
    /model      show active provider/model configuration
    /provider   switch provider (ollama | gemini)
    /exit       quit
"""

# Allows modern Python type annotations to be evaluated lazily.
from __future__ import annotations

# Import Python's system module.
# It is used to display errors and terminate the application.
import sys

# Import TypedDict to define the structure of the graph's shared state.
from typing import TypedDict

# StrOutputParser converts the language model's response into plain text.
from langchain_core.output_parsers import StrOutputParser

# Import LangGraph components:
# END       - marks the end of the graph.
# START     - marks the beginning of the graph.
# StateGraph - creates a graph that operates using shared state.
from langgraph.graph import END, START, StateGraph

# Import shared application modules.
# config        - manages environment and model configuration.
# model_factory - creates the selected LLM.
# prompts       - contains system prompts for different finance categories.
# schemas       - contains Pydantic schemas used for structured output.
from common import config, model_factory, prompts, schemas


# ==========================================================================
# 1. STATE - extended with routing fields
# ==========================================================================

# Define the structure of the information shared between graph nodes.
# TypedDict specifies the expected keys and data types of a dictionary.
class FinanceState(TypedDict):

    # Documentation describing the purpose of the state fields.
    """State schema for the V3 routing workflow.

    Fields
    ------
    question      : raw employee question (set at START)
    category      : classification result, e.g. "invoice"  (set by classifier)
    routed_answer : answer produced by the selected category node
    final_output  : formatted reply written by the output node
    """

    # Stores the original question entered by the employee.
    question: str

    # Stores the category assigned by the classifier.
    # Examples: invoice, budget, reimbursement or general.
    category: str

    # Stores the answer generated by the selected category node.
    routed_answer: str

    # Stores the final formatted response displayed to the user.
    final_output: str


# ==========================================================================
# 2. ROUTING TABLE - single source of truth for category -> node mapping
#    Used by:
#      * the conditional edge (path_map)
#      * the route_query() function
#      * classification validation (unknown categories become "general")
# ==========================================================================

# Create a dictionary that maps each finance category to its graph node.
# The dictionary is used to decide which node should execute.
#
# Example:
# If the category is "invoice", execution moves to "invoice_node".
ROUTES: dict[str, str] = {
    "expense_policy": "policy_node",
    "invoice": "invoice_node",
    "reimbursement": "reimbursement_node",
    "budget": "budget_node",
    "general": "general_node",
    "unclear": "clarification_node",
}


# ==========================================================================
# 3. CLASSIFIER PROMPT (local to this session - the router's instructions)
# ==========================================================================

# Define the system instructions that tell the LLM how to classify questions.
# This prompt is separate from the prompts used to generate finance answers.
CLASSIFIER_SYSTEM = (

    # Explain the role of the model and ask it to assign one category.
    "You are a query classifier for FinDesk, a corporate finance operations "

    # Continue the instructions and restrict the possible categories.
    "assistant. Read the employee's question and assign exactly one "

    # List all permitted classification categories.
    "category from: expense_policy, invoice, reimbursement, budget, general, "
    "unclear.\n"

    # Define what an expense policy question looks like.
    "- expense_policy : rules/limits of corporate expense, travel, "
    "vendor-payment or procurement policies\n"

    # Define questions related to invoices and purchase orders.
    "- invoice        : invoice documents, invoice review, missing fields, "
    "vendor bills, purchase orders\n"

    # Define questions related to employee reimbursements.
    "- reimbursement  : employee expense claims, refunds, travel claims\n"

    # Define questions related to budgets and spending.
    "- budget         : budget, utilisation, variance, department spend\n"

    # Define general finance questions that do not fit other categories.
    "- general        : finance terms, document differences, process "
    "overviews that fit none of the above\n"

    # Define questions that are too vague or outside the finance domain.
    "- unclear        : too vague or not a finance question"
)


# ==========================================================================
# 4. KEYWORD FALLBACK CLASSIFIER
#    Structured LLM output behaves differently across providers; this pure-
#    Python function guarantees the graph still routes when the LLM call
#    fails, is unavailable, or returns an unexpected shape.
# ==========================================================================

# Define keyword rules for classification.
# Each entry contains:
# 1. A category name.
# 2. A tuple containing words or phrases associated with that category.
#
# The rules are checked from top to bottom.
# The first matching category is returned.
KEYWORD_RULES: list[tuple[str, tuple[str, ...]]] = [

    # Keywords associated with invoices and purchase orders.
    ("invoice", ("invoice", "inv-", "purchase order", "vendor bill",
                 "3-way", "three-way", "grn")),

    # Keywords associated with employee reimbursement claims.
    ("reimbursement", ("reimbursement", "reimburse", "expense claim",
                       "claim form", "travel claim", "refund")),

    # Keywords associated with budgets and financial utilisation.
    ("budget", ("budget", "utilisation", "utilization", "variance",
                "spent", "remaining balance")),

    # Keywords associated with expense and travel policies.
    ("expense_policy", ("policy", "allowance", "limit", "guideline",
                        "travel policy", "expense rules")),
]


# Define a function that classifies a question using keyword matching.
# It is used when LLM-based structured classification fails.
def keyword_classify(question: str) -> str:

    # Documentation describing the function's input and output.
    """Rule-based classification used as the provider-safe fallback.

    Parameters
    ----------
    question : str
        The employee's raw question.

    Returns
    -------
    str
        One of the keys of ROUTES.
    """

    # Convert the question to lowercase.
    # This makes keyword matching independent of letter case.
    # For example, "INVOICE" and "invoice" are treated equally.
    text = question.lower()

    # 1. Check the keyword rules in their defined order.
    # category receives the category name.
    # keywords receives the tuple of words for that category.
    for category, keywords in KEYWORD_RULES:

        # any() checks whether at least one keyword is present in the text.
        # It returns True as soon as a matching keyword is found.
        if any(kw in text for kw in keywords):

            # Return the category as soon as a keyword matches.
            return category

    # 2. If no keyword matches, check the number of words.
    # split() separates the question into individual words.
    # len() counts how many words are present.
    if len(text.split()) < 2:

        # If the question contains fewer than two words,
        # classify it as unclear.
        return "unclear"

    # 3. If no keyword matches and the question has at least two words,
    # classify it as a general question.
    return "general"


