# Define a function that creates and compiles the complete LangGraph workflow.
# provider specifies whether Gemini or Ollama should be used.
# None means that the provider configured in .env will be used.
def build_app(provider: str | None = None):

    # Create the selected language model using the model factory.
    llm = model_factory.get_llm(provider)

    # --- classifier: asks the model for a QueryClassification object ------

    # Create a classification chain using LCEL.
    # The first component prepares the classification prompt.
    # The second component calls the LLM and requests structured output.
    #
    # QueryClassification is a Pydantic schema defined in common/schemas.py.
    # It specifies the expected structure of the classification response.
    classifier_chain = (

        # Prepare the prompt using the classification instructions.
        prompts.finance_prompt(CLASSIFIER_SYSTEM)

        # Connect the prompt to the LLM with structured output enabled.
        # The model is expected to return a QueryClassification object.
        | llm.with_structured_output(schemas.QueryClassification)
    )


    # ------------------------------------------------------------------
    # NODE: classifier
    # 1. Try the LLM structured classification.
    # 2. On ANY failure (provider quirks, network, bad JSON) fall back to
    #    the keyword rules so routing always produces a valid category.
    # 3. Validate the category against ROUTES - unknown values -> "general".
    # ------------------------------------------------------------------

    # Define the classifier node.
    # It receives the current graph state and returns a dictionary update.
    def classify_query(state: FinanceState) -> dict:

        # Retrieve the original question from the graph state.
        question = state["question"]

        # Declare that category will hold a string value.
        # The actual value will be assigned inside the try or except block.
        category: str

        # Try to classify the question using the LLM.
        try:

            # Execute the classification chain.
            # The question is inserted into the prompt's question placeholder.
            result = classifier_chain.invoke({"question": question})

            # with_structured_output() normally returns a Pydantic object.
            # However, some integrations may return a dictionary.
            # Check whether the result is a dictionary.
            if isinstance(result, dict):

                # If it is a dictionary, retrieve its category value.
                # get() returns an empty string if category is missing.
                # str() converts the result to a string.
                # lower() converts it to lowercase.
                category = str(result.get("category", "")).lower()

            # If the result is not a dictionary, treat it as an object.
            else:

                # getattr() retrieves the category attribute from the object.
                # If the attribute does not exist, it returns an empty string.
                # Convert the value to lowercase text.
                category = str(getattr(result, "category", "")).lower()

        # Handle errors during LLM-based classification.
        except Exception as exc:

            # Display the exception type and indicate that keyword matching
            # will be used instead of the LLM classifier.
            print(f"  [classifier LLM failed: {type(exc).__name__}; "
                  f"using keyword fallback]")

            # Classify the question using the predefined keyword rules.
            category = keyword_classify(question)

        # Check whether the returned category exists in the ROUTES dictionary.
        if category not in ROUTES:

            # If the LLM returned an unknown or invalid category,
            # use the keyword classifier as a fallback.
            category = keyword_classify(question)

        # Return the selected category as a graph state update.
        return {"category": category}


    # ------------------------------------------------------------------
    # NODE FACTORY: creates one answer node per category.
    # Six nearly identical node functions would duplicate code; instead we
    # build them from the system prompts declared in common/prompts.py.
    # Each returned function closes over its own prompt chain.
    # ------------------------------------------------------------------

    # Define a node factory.
    # A node factory is a function that creates and returns other functions.
    #
    # system_message contains the instructions for a particular category.
    # name contains the name to assign to the generated node function.
    def make_answer_node(system_message: str, name: str):

        # Build an LCEL chain using the supplied category-specific prompt.
        # The chain consists of:
        # Prompt -> LLM -> StrOutputParser.
        #
        # Each generated node will use its own prompt instructions.
        chain = prompts.finance_prompt(system_message) | llm | StrOutputParser()

        # Define the actual graph node inside the factory function.
        # This inner function can access the chain created above.
        def node(state: FinanceState) -> dict:

            # Send the original question to the category-specific LLM chain.
            # The chain generates an answer based on its system instructions.
            answer = chain.invoke({"question": state["question"]})

            # Return the generated answer as a state update.
            return {"routed_answer": answer}

        # Assign a meaningful name to the generated function.
        # This helps identify the node in graph visualizations.
        node.__name__ = name

        # Return the generated node function to the caller.
        return node


    # Create the expense policy node using the policy-specific prompt.
    policy_node = make_answer_node(prompts.POLICY_SYSTEM, "policy_node")

    # Create the invoice node using the invoice-specific prompt.
    invoice_node = make_answer_node(prompts.INVOICE_SYSTEM, "invoice_node")

    # Create the reimbursement node using its specific system prompt.
    reimbursement_node = make_answer_node(
        prompts.REIMBURSEMENT_SYSTEM, "reimbursement_node")

    # Create the budget node using the budget-specific system prompt.
    budget_node = make_answer_node(prompts.BUDGET_SYSTEM, "budget_node")

    # Create the general finance node using the general-purpose system prompt.
    general_node = make_answer_node(prompts.GENERAL_SYSTEM, "general_node")


    # ------------------------------------------------------------------
    # NODE: clarification
    # For "unclear" questions we do NOT call the model again - a fixed,
    # deterministic template is cheaper and cannot hallucinate policy.
    # ------------------------------------------------------------------

    # Define a node that handles unclear or insufficient questions.
    def clarification_node(state: FinanceState) -> dict:

        # Prepare a fixed clarification message.
        # No LLM call is made in this node.
        message = (

            # Explain that the finance topic could not be identified.
            "I could not identify a specific finance topic in your request.\n"

            # Introduce the types of questions FinDesk can handle.
            "FinDesk can help with:\n"

            # List the supported expense and travel policy topics.
            "  - expense and travel policies\n"

            # List the supported invoice and purchase order topics.
            "  - invoices and purchase orders\n"

            # List the supported reimbursement topics.
            "  - reimbursement claims\n"

            # List the supported budget topics.
            "  - budgets and utilisation\n"

            # Ask the user to rephrase the question and provide an example.
            "Please rephrase your question, e.g. "
            "'What is the hotel expense limit?'"
        )

        # Return the clarification message as the routed answer.
        return {"routed_answer": message}


    # ------------------------------------------------------------------
    # NODE: final output
    # All category nodes converge here; it formats category + answer.
    # ------------------------------------------------------------------

    # Define the final output node.
    # This node receives the category and answer from the previous node.
    def final_output(state: FinanceState) -> dict:

        # Retrieve the selected category.
        # If category is missing, use "general" as the default.
        category = state.get("category", "general")

        # Retrieve the generated answer.
        # If routed_answer is missing, use an empty string.
        # strip() removes unnecessary spaces at the beginning and end.
        answer = state.get("routed_answer", "").strip()

        # Add the category label before the answer.
        # \n inserts a new line between the label and the answer.
        #
        # Return the formatted text as a graph state update.
        return {"final_output": f"FinDesk [{category}]:\n{answer}"}


    # ------------------------------------------------------------------
    # ROUTING FUNCTION for the conditional edge
    # LangGraph calls this after the classifier node and expects a string
    # that matches one of the path_map keys (a category name).
    # ------------------------------------------------------------------

    # Define the function that decides which node should execute next.
    def route_query(state: FinanceState) -> str:

        # Retrieve the classification result from the state.
        # Use "general" if the category is missing.
        category = state.get("category", "general")

        # Check whether the category exists in ROUTES.
        # If valid, return it.
        # Otherwise, return "general" as a safe default.
        #
        # This returned category is used by LangGraph to select the next node.
        return category if category in ROUTES else "general"


    # ------------------------------------------------------------------
    # WIRE THE GRAPH
    # add_conditional_edges(source, path, path_map):
    #   source : node whose completion triggers the decision
    #   path   : function called with the state -> returns a path key
    #   path_map: {path key -> destination node}
    # ------------------------------------------------------------------

    # Create the graph builder using FinanceState as the shared state schema.
    builder = StateGraph(FinanceState)

    # Register the classifier node with the graph.
    builder.add_node("classify_query", classify_query)

    # Register the expense policy processing node.
    builder.add_node("policy_node", policy_node)

    # Register the invoice processing node.
    builder.add_node("invoice_node", invoice_node)

    # Register the reimbursement processing node.
    builder.add_node("reimbursement_node", reimbursement_node)

    # Register the budget processing node.
    builder.add_node("budget_node", budget_node)

    # Register the general finance processing node.
    builder.add_node("general_node", general_node)

    # Register the clarification node.
    builder.add_node("clarification_node", clarification_node)

    # Register the final output formatting node.
    builder.add_node("final_output", final_output)

    # Connect the START point to the classifier node.
    # Every question first passes through classification.
    builder.add_edge(START, "classify_query")

    # Add conditional routing after the classifier node.
    # LangGraph calls route_query() to determine the category.
    # ROUTES maps the returned category to the destination node.
    builder.add_conditional_edges(

        # The conditional decision happens after classification.
        "classify_query",

        # This function reads the category and returns a routing key.
        route_query,

        # This dictionary maps each routing key to its destination node.
        ROUTES,
    )

    # Every category node connects to the final output node.
    # ROUTES.values() gives us all the destination node names.
    # set() removes any duplicate node names.
    for node_name in set(ROUTES.values()):

        # Connect the current category node to final_output.
        builder.add_edge(node_name, "final_output")

    # Connect the final output node to END.
    builder.add_edge("final_output", END)

    # Compile the graph builder into an executable LangGraph application.
    return builder.compile()


