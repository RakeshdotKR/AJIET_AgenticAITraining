# Define a helper function to display the graph structure.
def print_graph(app) -> None:

    # Documentation describing the function.
    """Print the graph structure (ASCII art when available)."""

    # Retrieve the graph structure from the compiled application.
    graph = app.get_graph()

    # Try to display the graph as an ASCII diagram.
    try:

        # draw_ascii() creates a text-based visualization of the graph.
        print(graph.draw_ascii())

    # If ASCII rendering fails, display the graph information in text form.
    except Exception:

        # Print the names of the registered graph nodes.
        print("Nodes :", [n for n in graph.nodes])

        # Print the connections between nodes.
        # e.source is the starting node.
        # e.target is the destination node.
        print("Edges :", [(e.source, e.target) for e in graph.edges])


# Define a helper function that executes the graph and displays
# the updates produced by individual nodes.
def run_with_trace(app, question: str) -> None:

    # Documentation describing the execution trace.
    """Run the graph once, printing every node update (stream_mode='updates').

    Each yielded dict is {"node_name": {keys that node changed}}. We merge
    those updates into our own copy of the state - exactly what LangGraph
    does internally - so no second model call is needed at the end.
    """

    # Display the question that will be processed.
    print(f"  question: {question}")

    # Create the initial state dictionary.
    # At the beginning, only the original question is available.
    state: dict = {"question": question}

    # Execute the graph using stream().
    # stream_mode="updates" returns the updates produced by each node.
    for step in app.stream(state, stream_mode="updates"):

        # Each step contains the node name and the dictionary it returned.
        for node_name, update in step.items():

            # Display the name of the executed node and its state update.
            print(f"  -> node '{node_name}' updated: {update}")

            # Merge the node's updated values into the local state dictionary.
            # Existing keys are replaced, and new keys are added.
            state.update(update)

    # Display the final response after all graph nodes have executed.
    # If final_output is missing, display "(no output)" instead.
    print(f"  {state.get('final_output', '(no output)')}\n")


# Define a function that displays the model provider selection menu.
def choose_provider() -> str | None:

    # Documentation describing the provider menu.
    """Model menu - same UX as D1P1/D1P2."""

    # Display a separator line.
    print("=" * 60)

    # Display the application name.
    print("FinDesk V3 - Finance Query Routing Assistant")

    # Display another separator line.
    print("=" * 60)

    # Display the current provider and model configuration.
    print(f"Active configuration: {config.describe()}")

    # Display the provider selection heading.
    print("\nSelect model:")

    # Option 1: Use Gemini, which runs through Google's cloud service.
    print("  1. Gemini   (cloud, requires GOOGLE_API_KEY in .env)")

    # Option 2: Use Ollama, which runs models locally.
    print("  2. Ollama   (local, default)")

    # Option 3: Use the provider configured in the .env file.
    print(f"  3. Use .env default (currently: {config.LLM_PROVIDER})")

    # Read the user's selection.
    # strip() removes spaces before and after the entered value.
    choice = input("Choice [3]: ").strip()

    # If the user enters 1, select Gemini.
    if choice == "1":
        return "gemini"

    # If the user enters 2, select Ollama.
    if choice == "2":
        return "ollama"

    # For option 3, an empty input or any invalid input,
    # use the provider configured in .env.
    return None


